#!/usr/bin/env bash
set -euo pipefail

# AI Workflow — personal config installer.
#
# The skills and the reviewer agent ship as the `wf` Claude Code plugin and
# are installed with `claude plugin install` (see README). A plugin cannot
# carry the things below, so this script symlinks them from this clone:
#
#   dotfiles/CLAUDE.md      -> $CLAUDE_DIR/CLAUDE.md
#   settings.json           -> $CLAUDE_DIR/settings.json   (primary dir only)
#
# With --codex it also sets up OpenAI Codex, which reads AGENTS.md and custom
# agent files rather than CLAUDE.md and plugin agents:
#
#   dotfiles/CLAUDE.md      -> $CODEX_HOME/AGENTS.md              (symlink)
#   agents/reviewer.md      -> $CODEX_HOME/agents/wf-reviewer.toml (generated)
#
# Usage:
#   ./install.sh                  Link the files above
#   ./install.sh --extra          Also link the personal skills under extras/
#   ./install.sh --no-settings    Never link settings.json
#   ./install.sh --with-settings  Always link settings.json
#   ./install.sh --codex          Also set up Codex (see above)
#
# CODEX_HOME selects the Codex config dir (default ~/.codex). CLAUDE_DIR selects the Claude config dir (default ~/.claude). settings.json
# carries a profile's account, theme, model and enabled plugins, so by default
# it is linked only into the primary dir; a secondary profile keeps its own.

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# Resolve a directory to its canonical form so that ~/.claude, ~/.claude/ and a
# symlinked ~/.claude all compare equal — the primary-dir comparison below
# decides whether settings.json is shared.
canonical_dir() {
    local d="${1%/}"
    [ -z "$d" ] && d="/"
    if [ -d "$d" ]; then (cd -P "$d" && pwd); else printf '%s\n' "$d"; fi
}

PRIMARY_CLAUDE_DIR="$(canonical_dir "$HOME/.claude")"
CLAUDE_DIR="$(canonical_dir "${CLAUDE_DIR:-$HOME/.claude}")"

CODEX_DIR="${CODEX_HOME:-$HOME/.codex}"

INSTALL_EXTRAS=0
INSTALL_CODEX=0
INSTALL_SETTINGS=""
for arg in "$@"; do
    case "$arg" in
        --extra|--extras) INSTALL_EXTRAS=1 ;;
        --codex)          INSTALL_CODEX=1 ;;
        --no-settings)    INSTALL_SETTINGS=0 ;;
        --with-settings)  INSTALL_SETTINGS=1 ;;
        *) echo "Unknown argument: $arg" >&2; exit 1 ;;
    esac
done
if [ -z "$INSTALL_SETTINGS" ]; then
    if [ "$CLAUDE_DIR" = "$PRIMARY_CLAUDE_DIR" ]; then INSTALL_SETTINGS=1; else INSTALL_SETTINGS=0; fi
fi

GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m'
info() { echo -e "${GREEN}[+]${NC} $1"; }
warn() { echo -e "${YELLOW}[!]${NC} $1"; }

# link_abs <absolute source> <absolute destination>
link_abs() {
    local src="$1"
    local dst="$2"
    mkdir -p "$(dirname "$dst")"
    if [ -L "$dst" ] && [[ "$(readlink "$dst")" == "$SCRIPT_DIR"/* ]]; then
        rm "$dst"
    elif [ -e "$dst" ] || [ -L "$dst" ]; then
        local backup
        backup="${dst}.bak.$(date +%s)"
        warn "Backing up existing $dst -> $backup"
        mv "$dst" "$backup"
    fi
    ln -s "$src" "$dst"
    info "Linked $dst -> $src"
}

link() { link_abs "$SCRIPT_DIR/$1" "$CLAUDE_DIR/$2"; }

# First line of the generated Codex agent; uninstall removes only files that
# carry it.
CODEX_MARKER="# Generated by ai-workflow install.sh from agents/reviewer.md. Do not edit; re-run ./install.sh --codex."

# Write the Codex custom agent for the reviewer. The frontmatter description
# becomes a TOML string; the body becomes developer_instructions as a
# multi-line literal string, so it needs no escaping and is the source verbatim.
generate_reviewer_toml() {
    local src="$SCRIPT_DIR/agents/reviewer.md"
    local dst="$CODEX_DIR/agents/wf-reviewer.toml"
    local tmp desc backup lit="'''"
    [ -f "$src" ] || { echo "Missing $src" >&2; exit 1; }
    desc="$(awk 'NR==1 && $0!="---"{exit} NR>1 && $0=="---"{exit} /^description:/{sub(/^description:[ ]*/,""); print; exit}' "$src")"
    [ -n "$desc" ] || { echo "No description in $src frontmatter" >&2; exit 1; }
    desc="${desc//\\/\\\\}"
    desc="${desc//\"/\\\"}"
    mkdir -p "$(dirname "$dst")"
    tmp="$(mktemp "$dst.XXXXXX")"
    if ! DESC="$desc" awk -v marker="$CODEX_MARKER" -v lit="$lit" '
        BEGIN {
            print marker
            print "name = \"wf-reviewer\""
            print "description = \"" ENVIRON["DESC"] "\""
            print "developer_instructions = " lit
        }
        NR==1 && $0=="---" { fm=1; next }
        fm==1 { if ($0=="---") fm=2; next }
        { sub(/\r$/, ""); if (index($0, lit)) bad=1; print }
        END { print lit; exit bad }
    ' "$src" > "$tmp"; then
        rm -f "$tmp"
        echo "$src contains a triple single quote, which cannot go in a TOML literal string" >&2
        exit 1
    fi
    if [ -L "$dst" ] || { [ -e "$dst" ] && ! head -n1 "$dst" | grep -qxF "$CODEX_MARKER"; }; then
        backup="${dst}.bak.$(date +%s)"
        warn "Backing up existing $dst -> $backup"
        mv "$dst" "$backup"
    fi
    chmod 644 "$tmp"
    mv "$tmp" "$dst"
    info "Generated $dst from agents/reviewer.md"
}

mkdir -p "$CLAUDE_DIR"

link "dotfiles/CLAUDE.md" "CLAUDE.md"

# settings.json is per-user (gitignored). Seed it from the tracked example on a
# fresh clone so the symlink target exists.
if [ "$INSTALL_SETTINGS" -eq 1 ]; then
    if [ ! -e "$SCRIPT_DIR/settings.json" ]; then
        cp "$SCRIPT_DIR/settings.example.json" "$SCRIPT_DIR/settings.json"
        info "Seeded settings.json from settings.example.json (edit freely; not tracked)"
    fi
    link "settings.json" "settings.json"
else
    warn "Left settings.json alone (profile-local)"
fi

# Extras: personal add-ons outside the plugin. Multi-file skills are linked as
# whole directories so their supporting files resolve.
if [ "$INSTALL_EXTRAS" -eq 1 ]; then
    # shellcheck disable=SC2043 # a list that currently has one entry
    for skill in rlabs-design; do
        link "extras/skills/$skill" "skills/$skill"
    done
fi

if [ "$INSTALL_CODEX" -eq 1 ]; then
    mkdir -p "$CODEX_DIR"
    link_abs "$SCRIPT_DIR/dotfiles/CLAUDE.md" "$CODEX_DIR/AGENTS.md"
    generate_reviewer_toml
fi

echo ""
info "Done. Now install the plugin (skills + reviewer agent):"
echo "    claude plugin marketplace add rafagomes/ai-workflow"
echo "    claude plugin install wf@ai-workflow"
if [ "$INSTALL_CODEX" -eq 1 ]; then
    echo "  and for Codex:"
    echo "    codex plugin marketplace add rafagomes/ai-workflow"
    echo "    codex plugin add wf@ai-workflow     (or install wf from /plugins)"
    echo "    then start a NEW Codex session and trust the hook in /hooks"
fi
echo ""
